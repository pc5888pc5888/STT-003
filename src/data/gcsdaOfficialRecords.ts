export interface GcsdaCharterChapter { id: string; heading: string; articles: string[]; }

/** Keep every line of the founder-supplied, 114/07/01 assembly-approved charter. */
export const gcsdaCharterChapters: GcsdaCharterChapter[] = (() => {
  const chapters: GcsdaCharterChapter[] = [];
  let articleLines: string[] = [];
  let currentChapter: GcsdaCharterChapter | undefined;
  const commitArticle = () => {
    if (currentChapter && articleLines.length) currentChapter.articles.push(articleLines.join("\n"));
    articleLines = [];
  };
  for (const line of gcsdaCharterText.trim().split(/\r?\n/)) {
    if (/^【第[一二三四五六]章/.test(line)) {
      commitArticle();
      currentChapter = { id: "charter-chapter-" + (chapters.length + 1), heading: line, articles: [] };
      chapters.push(currentChapter);
    } else if (/^第[　\s]*[一二三四五六七八九十]+[　\s]*條/.test(line)) {
      commitArticle();
      articleLines.push(line);
    } else if (line.trim() && currentChapter) {
      articleLines.push(line);
    }
  }
  commitArticle();
  return chapters;
})();

